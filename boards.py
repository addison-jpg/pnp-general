#!/usr/bin/env python3
"""The boards as a data structure: a tree of findings laid over the tree of the repository.

A FINDING is one small record in a file `findings.jsonl` that lives in the directory of its evidence:
  {"id", "time", "who", "serves", "word", "statement", "evidence": ["path" | "path::name"], "by": [who checked it]}
  word is one of: checked | paper | tested | refuted | open | premise
A finding is VERIFIED when every evidence path exists, every `path::name` is found in that file, a
`checked` finding cites a .lean file, and (for anything but `checked`) at least one name in "by" differs
from "who". Only verified findings propagate UP: each directory's node holds the verified findings of
its subtree, counted by word. Unverified findings stay at their leaf.

  python3 -I boards.py                 rebuild boards/TREE.md and boards/tree.json
  python3 -I boards.py add DIR WHO SERVES WORD "STATEMENT" EVIDENCE [EVIDENCE ...]
  python3 -I boards.py confirm ID WHO  add WHO to "by" (a second seat reran or reread it)
Run from the repository root. `findings.jsonl` files merge by union (append only): no conflicts."""
import json, os, sys, time, hashlib, collections
WORDS = ["checked", "paper", "tested", "refuted", "open", "premise"]
SKIP = {".git", ".lake", "__pycache__", "node_modules"}

def leaves():
    for d, dirs, files in os.walk("."):
        dirs[:] = [x for x in dirs if x not in SKIP]
        if "findings.jsonl" in files: yield os.path.normpath(d)

def load(d):
    out = []
    for line in open(os.path.join(d, "findings.jsonl")):
        line = line.strip()
        if line: out.append(json.loads(line))
    last = {}
    for r in out: last[r["id"]] = {**last.get(r["id"], {}), **r, "by": sorted(set(last.get(r["id"], {}).get("by", [])) | set(r.get("by", [])))}
    return list(last.values())

def verified(r):
    why = []
    if r.get("word") not in WORDS: why.append("word")
    for e in r.get("evidence", []):
        path, _, name = e.partition("::")
        if not os.path.exists(path): why.append("missing " + path)
        elif name and name not in open(path, errors="ignore").read(): why.append(name + " not in " + path)
    if not r.get("evidence"): why.append("no evidence")
    if r.get("word") == "checked":
        if not any(e.partition("::")[0].endswith(".lean") for e in r.get("evidence", [])): why.append("checked needs a .lean file")
    elif not [b for b in r.get("by", []) if b != r.get("who")]: why.append("needs a second seat in by")
    return why

def build():
    node = collections.defaultdict(lambda: {"own": [], "up": []})
    for d in leaves():
        for r in load(d):
            r["dir"] = d; r["why_not"] = verified(r); node[d]["own"].append(r)
            if not r["why_not"]:
                p = d
                while True:
                    node[p]["up"].append(r)
                    if p in (".", ""): break
                    p = os.path.dirname(p) or "."
    tree = {d: {"counts": dict(collections.Counter(r["word"] for r in v["up"])),
                "verified": [r["id"] for r in v["up"]],
                "unverified_here": [{"id": r["id"], "why": r["why_not"]} for r in v["own"] if r["why_not"]]}
            for d, v in sorted(node.items())}
    os.makedirs("boards", exist_ok=True)
    json.dump(tree, open("boards/tree.json", "w"), indent=1)
    out = ["# The board tree", "", "Generated by `python3 -I boards.py`; do not edit. A node is a directory of the repository;",
           "it shows the VERIFIED findings of its subtree, counted by word. Findings live in `findings.jsonl`",
           "next to their evidence. Unverified findings are listed only at their own directory, with the reason.", ""]
    for d, v in sorted(node.items()):
        depth = 0 if d == "." else d.count(os.sep) + 1
        c = collections.Counter(r["word"] for r in v["up"])
        out.append("#" * min(depth + 2, 6) + f" `{d}/` " + " · ".join(f"{c[w]} {w}" for w in WORDS if c[w]) )
        for r in v["own"]:
            mark = "VERIFIED" if not r["why_not"] else "unverified (" + "; ".join(r["why_not"]) + ")"
            out.append(f"- `{r['id']}` **{r['word']}** [{r['serves']}] {r['statement']} · evidence: " + ", ".join(f"`{e}`" for e in r["evidence"]) + f" · {r['who']}" + (", confirmed by " + ", ".join(b for b in r['by'] if b != r['who']) if [b for b in r['by'] if b != r['who']] else "") + f" · {mark}")
        out.append("")
    open("boards/TREE.md", "w").write("\n".join(out))
    tot = collections.Counter(r["word"] for r in node["."]["up"])
    print("nodes", len(node), "| verified at the root:", dict(tot), "| unverified:", sum(len(v["unverified_here"]) for v in tree.values()))

def add(d, who, serves, word, statement, evidence):
    assert word in WORDS, WORDS
    rid = hashlib.sha1((statement + d).encode()).hexdigest()[:8]
    r = {"id": rid, "time": time.strftime("%Y-%m-%d %H:%M", time.gmtime()), "who": who, "serves": serves, "word": word,
         "statement": statement, "evidence": evidence, "by": [who]}
    open(os.path.join(d, "findings.jsonl"), "a").write(json.dumps(r, ensure_ascii=False) + "\n"); print(rid)

def confirm(rid, who):
    for d in leaves():
        for r in load(d):
            if r["id"] == rid:
                open(os.path.join(d, "findings.jsonl"), "a").write(json.dumps({"id": rid, "by": [who]}) + "\n"); return
    sys.exit("no finding " + rid)

if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:1] == ["add"]: add(a[1], a[2], a[3], a[4], a[5], a[6:])
    elif a[:1] == ["confirm"]: confirm(a[1], a[2])
    build()
