#!/usr/bin/env python3
"""Write RESULTS.md: every verified finding in the centre, grouped by program, with its label, evidence and the
command that rechecks it. Generated from center/shards/*.jsonl, so it cannot drift from the board.
Run: python3 -I center.py && python3 -I results.py"""
import collections, glob, json

ORDER = ["refuted", "checked", "checked-infinite", "checked-finite", "tested"]
recs = [json.loads(l) for f in sorted(glob.glob("center/shards/*.jsonl")) for l in open(f, encoding="utf-8")]
ok = [r for r in recs if r["kind"] == "finding" and not r.get("why_not") and r.get("word") in ORDER]
by = collections.defaultdict(list)
for r in ok: by[r["program"]].append(r)
out = ["# Results", "",
       "Generated by `results.py` from the centre store (`center/`). Only **verified** findings appear: every evidence path",
       "exists, and anything but a Lean proof has a second, independent seat. Labels: **checked** (a Lean proof),",
       "**checked-finite** (exact and exhaustive over a stated finite set), **tested** (sampled or numerical), **refuted**",
       "(a counterexample is in the repository). Unverified findings stay on the board (`boards/TREE.md`).", "",
       "| program | checked | checked-finite | tested | refuted |", "|---|---|---|---|---|"]
for p in sorted(by):
    c = collections.Counter(r["word"] for r in by[p])
    out.append(f"| {p} | {c['checked'] + c['checked-infinite']} | {c['checked-finite']} | {c['tested']} | {c['refuted']} |")
tot = collections.Counter(r["word"] for r in ok)
out.append(f"| **all** | **{tot['checked'] + tot['checked-infinite']}** | **{tot['checked-finite']}** | **{tot['tested']}** | **{tot['refuted']}** |")
for p in sorted(by):
    out += ["", f"## {p}", "", "| label | statement | evidence | recheck |", "|---|---|---|---|"]
    for r in sorted(by[p], key=lambda r: (ORDER.index(r["word"]), r["text"])):
        txt = " ".join(r["text"].split()).replace("|", "\\|")
        txt = txt if len(txt) <= 300 else txt[:297] + "..."
        ev = ", ".join(f"`{e}`" for e in r.get("evidence", [])[:3])
        run = f"`{r['runner']}`" if r.get("runner") else ""
        out.append(f"| {r['word']} | {txt} | {ev} | {run} |")
open("RESULTS.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(ok), "verified findings ->", "RESULTS.md", dict(tot))
