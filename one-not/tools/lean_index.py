#!/usr/bin/env python3
"""Searchable index of Lean declarations (name, kind, file:line, first docstring sentence, signature head).

Usage: python3 tools/lean_index.py [ROOT=lean/PEqualNP] [DIR ...] > index.md
Default DIRs: Kernel Base W951. Grep the output before writing a helper: if a lemma with the
shape you need exists, import it instead of re-proving it.
"""
import os
import re
import sys

DECL = re.compile(
    r'^(?:@\[[^\]]*\]\s*)?(?:(?:private|protected|noncomputable|nonrec)\s+)*'
    r'(theorem|lemma|def|abbrev|structure|inductive|class|instance)\s+([^\s:({\[]+)')
NS = re.compile(r'^namespace\s+(\S+)')
END = re.compile(r'^end\s+(\S+)')


def scan(path):
    out, ns, doc = [], [], None
    lines = open(path, encoding='utf-8').read().split('\n')
    i = 0
    while i < len(lines):
        line = lines[i]
        m = NS.match(line)
        if m:
            ns.append(m.group(1))
        m = END.match(line)
        if m and ns and ns[-1] == m.group(1):
            ns.pop()
        if line.lstrip().startswith('/--'):
            buf = [line.strip()[3:]]
            while '-/' not in buf[-1] and i + 1 < len(lines):
                i += 1
                buf.append(lines[i].strip())
            text = ' '.join(buf).replace('-/', '').strip()
            doc = re.split(r'(?<=[.!?])\s', text, maxsplit=1)[0][:160]
            i += 1
            continue
        m = DECL.match(line)
        if m and 'private' not in line.split(m.group(1))[0]:
            sig = line.strip()
            j = i
            while ':=' not in sig and ' where' not in sig and j + 1 < len(lines) and j - i < 6:
                j += 1
                sig += ' ' + lines[j].strip()
            sig = re.sub(r'\s+', ' ', sig.split(':=')[0])
            sig = re.split(r' @\[| \| | where\b', sig)[0][:220]
            out.append((m.group(1), m.group(2), i + 1, doc or '', sig))
        if line.strip() and not line.lstrip().startswith('@['):
            if not line.lstrip().startswith('/--'):
                doc = None if not m else doc
            if m:
                doc = None
        i += 1
    return out


def main():
    args = sys.argv[1:]
    root = args[0] if args and os.path.isdir(args[0]) and not os.path.isdir(os.path.join('lean/PEqualNP', args[0])) else 'lean/PEqualNP'
    dirs = [a for a in args if a != root] or ['Kernel', 'Base', 'W951']
    print('# Lean declaration index\n')
    print('Generated by tools/lean_index.py. Grep before you write a helper.\n')
    for d in dirs:
        base = os.path.join(root, d)
        if not os.path.isdir(base):
            continue
        print(f'## {d}\n')
        for dp, _, fs in sorted(os.walk(base)):
            for f in sorted(fs):
                if not f.endswith('.lean'):
                    continue
                p = os.path.join(dp, f)
                decls = scan(p)
                if not decls:
                    continue
                print(f'### {os.path.relpath(p, root)} ({len(decls)})\n')
                for kind, name, line, doc, sig in decls:
                    extra = f' — {doc}' if doc else ''
                    print(f'- `{name}` ({kind}, :{line}){extra}  \n  `{sig}`')
                print()


if __name__ == '__main__':
    main()
