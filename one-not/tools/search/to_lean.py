"""Turn a circuit JSON {"n","sets","gates":[[op,a,b?]..],"outs"} into Lean: a circuit literal and the
two theorems `<NAME>_correct` and `<NAME>_witness` (checked by `decide +kernel`).
Usage: python3 -I to_lean.py FILE.json NAME > one-not/lean/PEqualNP/W951/SearchCheck_<NAME>.lean
The witness count is also computed here in Python (independent twin) and written into the theorem;
if Lean disagrees, the build fails (Python only proposes, Lean decides)."""
import json, sys, itertools

def tables(d):
    n = d["n"]; N = 1 << n; full = (1 << N) - 1
    w = [sum(((r >> i) & 1) << r for r in range(N)) for i in range(n)]
    for g in d["gates"]:
        a = w[g[1]]
        if g[0] == "not": w.append(full ^ a)
        else:
            b = w[g[2]]
            w.append(a & b if g[0] == "and" else a | b)
    return w

def witness_count(d):
    n = d["n"]; N = 1 << n; w = tables(d); cnt = 0
    for g in range(n, len(w)):
        T = w[g]; hit = False
        for S in d["sets"]:
            for u, v in itertools.combinations(S, 2):
                for r in range(N):
                    if any((r >> s) & 1 for s in S): continue
                    if not (T >> r) & 1 and (T >> (r | 1 << u)) & 1 and (T >> (r | 1 << v)) & 1:
                        hit = True
        cnt += hit
    return cnt

def main():
    d = json.load(open(sys.argv[1])); name = sys.argv[2]
    op = {"and": 0, "or": 1, "not": 2}
    gl = ", ".join(f"⟨{op[g[0]]}, {g[1]}, {g[2] if len(g) > 2 else g[1]}⟩" for g in d["gates"])
    sets = "[" + ", ".join("[" + ", ".join(map(str, S)) + "]" for S in d["sets"]) + "]"
    outs = "[" + ", ".join(map(str, d["outs"])) + "]"
    cnt = witness_count(d)
    print(f"""import PEqualNP.W951.SearchCheck
/-! Generated by one-not/tools/search/to_lean.py from {sys.argv[1].split('/')[-1]}. Do not edit.
Definitional check only; see PEqualNP/W951/SearchCheck.lean for what is and is not proved. -/
namespace SearchCheck.{name}
def {name} : Circ := ⟨{d['n']}, {sets}, {outs}, [{gl}]⟩
theorem {name}_correct : correctB {name} = true := by decide +kernel
theorem {name}_witness : witnessCount {name} = {cnt} := by decide +kernel
end SearchCheck.{name}""")
main()
