"""Every REGISTRY entry x every witness file with n <= 9: the margin, written to one-not/tools/search/registry_table.md.
Run from the repo root: python3 -I one-not/tools/search/run_all.py [max_n]   (default 9). Margin < 0 is shown in bold with CEX."""
import sys, os, json, glob, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from core import *
from conjectures import REGISTRY

def main():
    maxn = int(sys.argv[1]) if len(sys.argv) > 1 else 9; names = list(REGISTRY); rows = []; neg = []
    for p in sorted(glob.glob('one-not/data/witnesses/**/*.json', recursive=True)):
        d = json.load(open(p))
        if not (isinstance(d, dict) and all(k in d for k in ('n', 'sets', 'gates', 'outs'))) or d['n'] > maxn: continue
        c = {"n": d['n'], "sets": d['sets'], "gates": [list(g) for g in d['gates']], "outs": d['outs']}
        if not correct(c): continue
        cells = []
        for nm in names:
            t = time.time()
            try: m, _ = REGISTRY[nm](c)
            except Exception as e: m = None
            cells.append("err" if m is None else (f"**{m} CEX**" if m < 0 else str(m)))
            if m is not None and m < 0: neg.append((p, nm, m))
        rows.append((os.path.relpath(p, 'one-not/data/witnesses'), c['n'], len(c['gates']), nots(c), base(c), cells))
    L = ["# Registry table (generated by run_all.py)", "",
         f"Margin of every REGISTRY entry on every correct witness file with n <= {maxn}. Margin < 0 = counterexample to that conjecture;",
         "a margin of 1 on the no-rewire predicate is vacuous (circuit not irreducible with a read NOT gate, or n > 8). Serves C2, C3, C4.", "",
         "| witness | n | gates | NOT | base | " + " | ".join(names) + " |", "|" + "---|" * (5 + len(names))]
    for r in rows: L.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} | " + " | ".join(r[5]) + " |")
    L += ["", f"Negative margins: {len(neg)}" + ("".join(f"\n- {p}: {nm} = {m}" for p, nm, m in neg))]
    open('one-not/tools/search/registry_table.md', 'w').write("\n".join(L) + "\n")
    print(len(rows), "files,", len(names), "entries,", len(neg), "negative margins")
if __name__ == "__main__": main()
