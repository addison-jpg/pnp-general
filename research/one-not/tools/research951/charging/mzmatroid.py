"""Is the family {M_z(w) : z zero point of S_w} the basis family of a matroid?  (research, no_minCE lit/LP angle)
M_z(w) (front Lemma M): union-find over S_w in circuit order; an OR gate g = a | b with g(z) = 0 merges iff both
children have nonempty S-sets supp(c) = {u in S_w : c(z + e_u) = 1} lying in different classes.
Checks: (1) |M_z(w)| = d_w for every z (reproduces Lemma M); (2) basis exchange on the distinct M_z(w);
(3) price-form dual on random prices: Σ_w min_z π(M_z(w)) <= π(gates); and how often the matroid-union cut condition
    Σ_w (r_w(G) - r_w(A)) <= |G \\ A| holds where r_w is the rank of the (putative) matroid generated by F_w.
Usage: python3 mzmatroid.py ../../w951/tests/instances/*.json  (instances on branch pytools-951 / coord-951)"""
import sys, json, itertools, random


def evaluate(n, gates, x):
    w = [(x >> i) & 1 for i in range(n)]
    for g in gates:
        if g[0] == 'not': w.append(1 - w[g[1]])
        elif g[0] == 'and': w.append(w[g[1]] & w[g[2]])
        else: w.append(w[g[1]] | w[g[2]])
    return w


def merge_set(n, gates, S, z):
    base = evaluate(n, gates, z)
    flips = {u: evaluate(n, gates, z | (1 << u)) for u in S}
    par = {u: u for u in S}
    def find(u):
        while par[u] != u:
            par[u] = par[par[u]]; u = par[u]
        return u
    M = []
    for k, g in enumerate(gates):
        wire = n + k
        if g[0] != 'or' or base[wire] != 0: continue
        sa = [u for u in S if flips[u][g[1]]]; sb = [u for u in S if flips[u][g[2]]]
        if not sa or not sb: continue
        ca = {find(u) for u in sa}; cb = {find(u) for u in sb}
        if ca & cb: continue
        M.append(k)
        roots = ca | cb; r0 = next(iter(roots))
        for r in roots: par[find(r)] = find(r0)
    return frozenset(M)


def is_exchange_family(F):
    Fs = set(F)
    for B1 in F:
        for B2 in F:
            for x in B1 - B2:
                if not any((B1 - {x}) | {y} in Fs for y in B2 - B1):
                    return False, (sorted(B1), sorted(B2), x)
    return True, None


if __name__ == '__main__':
    random.seed(1)
    for f in sys.argv[1:]:
        d = json.load(open(f)); n, gates, sets = d['n'], d['gates'], d['sets']
        fam = []; lemma_ok = True
        for S in sets:
            Smask = sum(1 << u for u in S)
            zs = [z for z in range(1 << n) if not z & Smask]
            F = set()
            for z in zs:
                M = merge_set(n, gates, S, z)
                if len(M) != len(S) - 1: lemma_ok = False
                F.add(M)
            fam.append(F)
        ex = [is_exchange_family(list(F)) for F in fam]
        # price dual on random prices (sanity; MergeFrac is reported CHECKED by front)
        worst = -1e9
        for _ in range(300):
            pi = [random.random() ** 3 for _ in gates]
            lhs = sum(min(sum(pi[g] for g in M) for M in F) for F in fam)
            worst = max(worst, lhs - sum(pi))
        print(f.split('/')[-1], f"n={n} s={len(gates)} base={sum(len(S)-1 for S in sets)}",
              "LemmaM", "ok" if lemma_ok else "FAIL",
              "| #distinct M_z per set", [len(F) for F in fam],
              "| exchange", ["yes" if e[0] else "NO" for e in ex],
              f"| max(Σmin π(M) - π(G)) over 300 random π = {worst:.3f}")
        bad = [e[1] for e in ex if not e[0]]
        if bad: print("   exchange violation example (B1, B2, x):", bad[0])
