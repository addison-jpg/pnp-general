"""Build results.md from research/data/*.json (whatever sizes have been run). python report.py"""
import json, math, os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from stats import summarize, pooled, bootstrap_ratio_diff, paired, verdict, spearman, settle_layers, half_info_layer, direction

ORDER = ["0.5B", "1.5B", "3B", "7B-q4"]
ALL = {"0.5B": "Qwen2.5-0.5B-Instruct, fp32", "1.5B": "Qwen2.5-1.5B-Instruct, fp32", "3B": "Qwen2.5-3B-Instruct, bf16",
       "7B-q4": "Qwen2.5-7B-Instruct, GGUF Q4_K_M (llama-cpp-python)"}
PENDING = {}   # label -> reason, filled by the command line: report.py 3B="pending (CPU held for S8)"
for arg in sys.argv[1:]:
    k, v = arg.split("=", 1); PENDING[k] = v

runs = {}
for lab in ORDER:
    p = os.path.join(HERE, "data", f"{lab}.json")
    if os.path.exists(p): runs[lab] = json.load(open(p))
labs = [l for l in ORDER if l in runs]

L = []
w = L.append
w("# Heavy Qwen instrument: results\n")
w("Generated by `research/ath_prompts/measure/heavy/report.py` from `research/data/<size>.json` (written by `run.py`). "
  "**There is no GPU on this machine** (4 CPU cores, 15 GB RAM). Every model here ran on CPU, under `nice -n 19` on 2 threads; "
  "the code picks a GPU unchanged when torch sees one. Weights live in a scratchpad and are not in the repository.\n")
w("Scoring: teacher-forced, nothing generated. Each text is scored after one document-start token (`<|endoftext|>`), so every "
  "token, the first included, gets a surprisal; total bits is the whole text's information content under the model. "
  "Bits per character and per whitespace word do not depend on the tokenizer; bits per token mostly measures the tokenizer. "
  "Entropy is the model's predictive entropy before each token (what it expected to be surprised by). "
  "CIs are 95% paired bootstrap over prompts (10,000 resamples); p is the exact two-sided Wilcoxon signed-rank test on per-prompt differences.\n")
w("| size | model | layers | status | CPU seconds for all texts |")
w("|---|---|---|---|---|")
for lab in ORDER:
    if lab in runs:
        r = runs[lab]; w(f"| {lab} | {ALL[lab]} | {r['n_layers'] or '-'} | run | {r['seconds']:.0f} |")
    else:
        w(f"| {lab} | {ALL[lab]} | | {PENDING.get(lab, 'not run')} | |")
w("")

# ---------- B1 ----------
S = {}
for lab in labs:
    b1 = runs[lab]["b1"]
    S[lab] = ([summarize(x["inf"], x["r_inf"]) for x in b1], [summarize(x["frm"], x["r_frm"]) for x in b1])

if "0.5B" in runs:
    b1 = runs["0.5B"]["b1"]
    ti = sum(len(x["r_inf"]["bits"]) for x in b1); tf = sum(len(x["r_frm"]["bits"]) for x in b1)
    ni = sum(sum(x["r_inf"]["bits"][1:]) for x in b1) * math.log(2) / (ti - 10)
    nf = sum(sum(x["r_frm"]["bits"][1:]) for x in b1) * math.log(2) / (tf - 10)
    w("## Replication of the first measurement (0.5B, old convention)\n")
    w(f"Old convention (first token unscored, no document-start token, nats per token over tokens 2..n): this run gives {ti} vs {tf} tokens "
      f"and {ni:.2f} vs {nf:.2f} nats/token (informal vs formal). `results.md` reported 236 vs 267 and 6.0 vs 4.6. "
      "(Here the first token has the document-start token as context, so tokens 2..n are scored with one more token of context; small differences come from that.)\n")

w("## B1: informal (Addison verbatim) against formal rewrites, 10 prompts\n")
w("Pooled over the 10 prompts: informal / formal, and the paired difference informal − formal with its bootstrap CI.\n")
w("| size | tokens | chars | words | bits | bits/token | bits/char | bits/word | entropy/token |")
w("|---|---|---|---|---|---|---|---|---|")
for lab in labs:
    A, B = S[lab]
    f = lambda k: f"{sum(a[k] for a in A):.0f} / {sum(b[k] for b in B):.0f}"
    g = lambda num, den: f"{pooled(A, num, den):.2f} / {pooled(B, num, den):.2f}"
    ent = lambda R: sum(r["ent_per_token"] * r["tokens"] for r in R) / sum(r["tokens"] for r in R)
    w(f"| {lab} | {f('tokens')} | {f('chars')} | {f('words')} | {f('bits')} | {g('bits', 'tokens')} | {g('bits', 'chars')} | {g('bits', 'words')} | {ent(A):.2f} / {ent(B):.2f} |")
w("")

CLAIMS = [
    ("B1a: informal has fewer tokens", "tokens", None, "per-prompt"),
    ("B1b: informal has more bits per token", "bits", "tokens", "pooled"),
    ("B1c: informal has more bits per character", "bits", "chars", "pooled"),
    ("B1d: informal has more bits per word", "bits", "words", "pooled"),
    ("B1e: informal costs fewer total bits (same instruction, less information to send)", "bits", None, "per-prompt"),
    ("entropy: the model expects more surprise on informal text (entropy per token)", "ent_tok", None, "pooled-ent"),
]
w("### Paired tests and verdict per claim\n")
w("Verdict rule (`stats.verdict`): *holds at every size* = the CI excludes 0 with the same sign at every size run; *reverses* = CIs exclude 0 with opposite signs at two sizes; "
  "*shrinks with size* = CI excludes 0 at the smallest size, includes 0 at the largest, with a smaller point estimate; *not resolved* = otherwise (CI includes 0). "
  "The sign column says whether the claimed direction is the one seen.\n")
VERD = {}
for name, num, den, kind in CLAIMS:
    w(f"**{name}**\n")
    w("| size | informal − formal | 95% CI | Wilcoxon p | prompts with informal > formal |")
    w("|---|---|---|---|---|")
    per = []
    for lab in labs:
        A, B = S[lab]
        if kind == "pooled":
            pt, lo, hi = bootstrap_ratio_diff(A, B, num, den)
            pp = paired(A, B, f"{num}_per_{den[:-1]}" if den != "chars" else "bits_per_char")
            pv, pos = pp["wilcoxon_p"], pp["pos"]
        elif kind == "pooled-ent":
            for X in (A, B):
                for r in X: r["ent_tok"] = r["ent_per_token"] * r["tokens"]
            pt, lo, hi = bootstrap_ratio_diff(A, B, "ent_tok", "tokens")
            pp = paired(A, B, "ent_per_token"); pv, pos = pp["wilcoxon_p"], pp["pos"]
        else:
            pp = paired(A, B, num); pt, lo, hi, pv, pos = pp["mean"], pp["lo"], pp["hi"], pp["wilcoxon_p"], pp["pos"]
        per.append((lab, pt, lo, hi))
        unit = "per prompt (mean)" if kind == "per-prompt" else "pooled"
        w(f"| {lab} | {pt:+.3f} {unit} | [{lo:+.3f}, {hi:+.3f}] | {pv:.3f} | {pos} of 10 |")
    want = "-" if name.startswith(("B1a", "B1e")) else "+"
    v = verdict(per); dirs = {direction(lo, hi) for _, _, lo, hi in per}
    sign = "claimed direction" if dirs <= {want, "0"} and want in dirs else ("opposite direction" if dirs <= {"-" if want == "+" else "+", "0"} and dirs - {"0"} else "no clear direction")
    VERD[name] = (v, sign)
    w(f"\nVerdict: **{v}**; {sign}.\n")

# preferences block (one item: no CI)
w("### The preferences block (one text, no CI)\n")
w("| size | tokens inf / frm | bits inf / frm | bits/char inf / frm | bits/token inf / frm |")
w("|---|---|---|---|---|")
for lab in labs:
    p = runs[lab]["prefs"]; a = summarize(p["inf"], p["r_inf"]); b = summarize(p["frm"], p["r_frm"])
    w(f"| {lab} | {a['tokens']} / {b['tokens']} | {a['bits']:.0f} / {b['bits']:.0f} | {a['bits_per_char']:.2f} / {b['bits_per_char']:.2f} | {a['bits_per_token']:.2f} / {b['bits_per_token']:.2f} |")
w("")

# agreement across sizes
if len(labs) >= 2:
    w("## Agreement across model sizes\n")
    w("Spearman rank correlation, across the 20 texts (10 informal + 10 formal), of bits per character; and across all tokens of the 20 texts, of per-token surprisal "
      "(the same tokenizer at every size, so tokens align).\n")
    w("| pair | texts, bits/char | tokens, surprisal |")
    w("|---|---|---|")
    for i in range(len(labs)):
        for j in range(i + 1, len(labs)):
            a, b = labs[i], labs[j]
            xa = [r["bits_per_char"] for r in S[a][0] + S[a][1]]; xb = [r["bits_per_char"] for r in S[b][0] + S[b][1]]
            ta, tb = [], []
            for u, v in zip(runs[a]["b1"], runs[b]["b1"]):
                for k in ("r_inf", "r_frm"):
                    if len(u[k]["bits"]) == len(v[k]["bits"]): ta += u[k]["bits"]; tb += v[k]["bits"]
            w(f"| {a} vs {b} | {spearman(xa, xb):.2f} | {spearman(ta, tb):.2f} (n = {len(ta)}) |")
    w("")

# logit lens
lensl = [l for l in labs if "lens_bits" in runs[l]["b1"][0]["r_inf"]]
if lensl:
    w("## Logit lens: how prediction builds up through the layers\n")
    w("After each layer the residual stream is decoded through the final RMSNorm and the unembedding, giving the probability of the actual next token at that depth "
      "(the last layer is the model's own output; `instrument.py` asserts they agree). Depth is the layer divided by the layer count.\n")
    w("**Mean surprisal of the actual next token (bits) by depth, informal / formal, pooled over all tokens of the 10 prompts:**\n")
    DEC = [0.25, 0.5, 0.75, 0.9, 1.0]
    w("| size | layers | " + " | ".join(f"depth {d:.2f}" for d in DEC) + " |")
    w("|---|---|" + "---|" * len(DEC))
    for lab in lensl:
        nl = runs[lab]["n_layers"]; cells = []
        for d in DEC:
            l = max(1, round(d * nl)) - 1
            mi = np.mean([b for x in runs[lab]["b1"] for b in x["r_inf"]["lens_bits"][l]])
            mf = np.mean([b for x in runs[lab]["b1"] for b in x["r_frm"]["lens_bits"][l]])
            cells.append(f"{mi:.1f} / {mf:.1f}")
        w(f"| {lab} | {nl} | " + " | ".join(cells) + " |")
    w("")
    w("**When tokens become predictable.** Two per-token measures: the *settle layer*, the first layer from which the lens top-1 is the actual token at every later layer "
      "(defined only for tokens the model gets right at the end, top-1); and the *half-information layer*, the first layer from which the lens surprisal stays at least halfway "
      "down from its first-layer value to its final value (defined for every token). Reported as depth (layer / layers); per prompt, the median over its tokens.\n")
    w("| size | register | tokens top-1 at the end | median settle depth | median half-information depth |")
    w("|---|---|---|---|---|")
    LENSP = {}
    for lab in lensl:
        nl = runs[lab]["n_layers"]
        for reg in ("r_inf", "r_frm"):
            st, hi_ = [], []
            for x in runs[lab]["b1"]:
                s, _ = settle_layers(x[reg]); h, _ = half_info_layer(x[reg])
                st += [v / nl for v in s if v is not None]; hi_ += [v / nl for v in h]
            tot = sum(len(x[reg]["bits"]) for x in runs[lab]["b1"])
            w(f"| {lab} | {'informal' if reg == 'r_inf' else 'formal'} | {len(st)} of {tot} | {np.median(st):.2f} | {np.median(hi_):.2f} |")
    w("")
    w("**Per prompt (largest lens size run): median half-information depth, informal / formal.**\n")
    lab = lensl[-1]; nl = runs[lab]["n_layers"]
    w(f"Size {lab}.\n")
    w("| prompt | informal | formal | settled top-1 informal / formal |")
    w("|---|---|---|---|")
    for x in runs[lab]["b1"]:
        hi_i = np.median([v / nl for v in half_info_layer(x["r_inf"])[0]]); hi_f = np.median([v / nl for v in half_info_layer(x["r_frm"])[0]])
        si = sum(v is not None for v in settle_layers(x["r_inf"])[0]); sf = sum(v is not None for v in settle_layers(x["r_frm"])[0])
        w(f"| {x['id']} | {hi_i:.2f} | {hi_f:.2f} | {si}/{len(x['r_inf']['bits'])} / {sf}/{len(x['r_frm']['bits'])} |")
    w("")

# interchange
w("## Human language against code: the same statement in English, asteroid (.ath) and Lean\n")
w("Five statements, each copied from the repository in three forms (sources in `data.py`). Total bits is what the content costs under the model; bits/char is the rate. "
  "If the three forms were interchangeable in information, their total bits would be about equal.\n")
w("| statement | size | chars E / A / L | tokens E / A / L | total bits E / A / L | bits/char E / A / L |")
w("|---|---|---|---|---|---|")
RAT = {}
for i, it in enumerate(runs[labs[0]]["interchange"] if labs else []):
    for lab in labs:
        f = runs[lab]["interchange"][i]["forms"]
        sm = {k: summarize(f[k]["text"], f[k]["r"]) for k in ("english", "ath", "lean")}
        RAT.setdefault(lab, []).append(sm)
        c = lambda k, fmt: " / ".join(format(sm[x][k], fmt) for x in ("english", "ath", "lean"))
        w(f"| {it['id']} | {lab} | {c('chars', 'd')} | {c('tokens', 'd')} | {c('bits', '.0f')} | {c('bits_per_char', '.2f')} |")
w("")
if RAT:
    w("Summary per size: geometric mean over the 5 statements of total-bits ratios.\n")
    w("| size | ath / English | Lean / English | Lean / ath | bits/char English, ath, Lean (pooled) |")
    w("|---|---|---|---|---|")
    for lab in labs:
        R = RAT[lab]
        gm = lambda a, b: math.exp(np.mean([math.log(r[a]["bits"] / r[b]["bits"]) for r in R]))
        pc = lambda k: sum(r[k]["bits"] for r in R) / sum(r[k]["chars"] for r in R)
        w(f"| {lab} | {gm('ath', 'english'):.2f} | {gm('lean', 'english'):.2f} | {gm('lean', 'ath'):.2f} | {pc('english'):.2f}, {pc('ath'):.2f}, {pc('lean'):.2f} |")
    w("")

NOTES = os.path.join(HERE, "notes.md")
if os.path.exists(NOTES): w(open(NOTES, encoding="utf-8").read())
open(os.path.join(HERE, "results.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L))
